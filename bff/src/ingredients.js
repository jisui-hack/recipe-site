/*
 * 材料の分類。**画像生成と下書きの整形で同じ判定を使う。**
 *
 * 別々に持つと「イラストでは調味料扱い、下書きでは具材扱い」のように
 * 食い違う。1か所にまとめておく。
 */

/** 皿の上にも味にも出ないもの。渡す意味がない */
const IGNORED = ["水", "お湯", "湯"];

const SEASONINGS = [
  "塩", "こしょう", "コショウ", "胡椒", "砂糖", "味の素",
  "醤油", "しょうゆ", "みりん", "酒", "酢", "みそ", "味噌",
  "油", "バター", "マヨネーズ", "ケチャップ", "ソース", "ポン酢", "めんつゆ",
  "だし", "出汁", "コンソメ", "鶏がら", "ナンプラー",
  "カレー粉", "山椒", "七味", "一味", "はちみつ", "蜂蜜",
  "片栗粉", "小麦粉",
  // 薬味・練り物。具材として渡すと山盛りで描かれる（わさびで実際に起きた）
  "わさび", "ワサビ", "からし", "辛子", "柚子胡椒", "ゆず胡椒",
  "豆板醤", "コチュジャン", "甜麺醤",
  "おろし生姜", "おろししょうが", "生姜チューブ", "しょうがチューブ",
  "おろしにんにく", "にんにくチューブ",
];

/**
 * 末尾で見るもの。
 * 「オリーブオイル」「ごま油」「カレールー」を落としたいが、
 * 部分一致だと「オイルサーディン」「ブルーベリー」まで巻き込む。
 */
const SEASONING_SUFFIX = ["油", "オイル", "ルー", "ルウ"];

/** 溶けて色と照りになるもの。皿の上で姿を持たない */
export function isSeasoning(name) {
  const n = String(name ?? "").trim();
  return (
    SEASONINGS.some((s) => n.includes(s)) ||
    SEASONING_SUFFIX.some((s) => n.endsWith(s))
  );
}

export function isIgnored(name) {
  const n = String(name ?? "").trim();
  return IGNORED.some((s) => n === s || n.startsWith(s));
}

/**
 * 調味料に分量の指定が無いときの既定。
 * 「醤油」だけで分量が空だと、投稿フォームで空欄のまま残り、
 * 見た目にも「書き忘れ」に見える。家庭料理では「適量」が普通の答え。
 */
export const DEFAULT_SEASONING_AMOUNT = "適量";

/* ---------- 調味料の使われ方 ---------- */

/** 仕上げに上へのせる・かける。皿の上に少量だけ見える */
const TOPPING = /(のせ|乗せ|添え|かけて|かける|散ら|振り|ふり|トッピング|飾|上に)/;

/** 「回しかける」「回し入れる」は調理中に加える動作。仕上げのトッピングではない */
const POUR_IN = /(回しかけ|回し入れ|まわしかけ|まわし入れ)/;

/**
 * 姿を持ちうる調味料。練り物・ペースト・粒。
 * 名前だけ渡すと具材のように山盛りで描かれる。
 * 液体（醤油・酒・油）は元から姿を持たないので、ここには入れない。
 */
const PASTE_OR_GRAIN = [
  "わさび", "ワサビ", "からし", "辛子", "柚子胡椒", "ゆず胡椒",
  "豆板醤", "コチュジャン", "甜麺醤", "みそ", "味噌",
  "おろし生姜", "おろししょうが", "生姜チューブ", "しょうがチューブ",
  "おろしにんにく", "にんにくチューブ",
  "マヨネーズ", "ケチャップ", "バター", "はちみつ", "蜂蜜",
  "山椒", "七味", "一味", "胡椒", "こしょう", "コショウ", "カレー粉",
];

export function isPasteOrGrain(name) {
  const n = bareName(name);
  return PASTE_OR_GRAIN.some((s) => n.includes(s));
}

/** 混ぜ込む・絡める・煮る。全体になじんで姿は見えない */
const MIX_IN = /(絡め|からめ|混ぜ|まぜ|溶か|和え|あえ|加え|入れ|炒め|煮|漬け|揉|もみ|下味|なじ)/;

/** 括弧の補足を外した素の名前。「山椒（または七味）」→「山椒」 */
function bareName(name) {
  return String(name ?? "").replace(/（[^）]*）/g, "").replace(/\([^)]*\)/g, "").trim();
}

/**
 * 手順を読んで、その調味料がどう使われるかを返す。
 *
 *   "topping" … 仕上げにのせる・かける → 少量が上に見える
 *   "mixed"   … 絡める・混ぜる・煮る   → 全体になじんで見えない
 *   null      … 手順に出てこない
 *
 * **同じ調味料でも見た目が変わる。** わさびを「加えて絡める」レシピで、
 * 炒め物の上に山盛りのわさびが描かれた。名前だけ渡していたのが原因。
 * 同じ文に「のせる」と「混ぜる」があれば、のせる方を優先する
 * （「混ぜてから上にのせる」は最終的に上にある）。
 */
export function seasoningUsage(name, steps) {
  const key = bareName(name);
  if (!key) return null;
  for (const step of steps ?? []) {
    for (const sentence of String(step ?? "").split(/(?<=。)/)) {
      if (!sentence.includes(key)) continue;
      if (POUR_IN.test(sentence)) return "mixed";
      if (TOPPING.test(sentence)) return "topping";
      if (MIX_IN.test(sentence)) return "mixed";
    }
  }
  return null;
}
